# Data generator to load images in batches
class DataGenerator(tf.keras.utils.Sequence):
    def __init__(self, data, images_dir, is_fruit=True, batch_size=16, target_size=(224, 224), **kwargs):
        super().__init__(**kwargs)
        self.data = data
        self.images_dir = images_dir
        self.is_fruit = is_fruit
        self.batch_size = batch_size
        self.target_size = target_size
        self.encoder = fruit_encoder if is_fruit else quality_encoder
        self.on_epoch_end = lambda: None

    def __len__(self):
        return len(self.data) // self.batch_size

    def __getitem__(self, index):
        start_idx = index * self.batch_size
        end_idx = (index + 1) * self.batch_size
        batch_data = self.data.iloc[start_idx:end_idx]

        images = []
        labels = []
        for _, row in batch_data.iterrows():
            img_path = os.path.join(self.images_dir, row['Image Name'])
            try:
                img = Image.open(img_path).resize(self.target_size)
                img = img_to_array(img) / 255.0
                images.append(img)
                label = row['Fruit'] if self.is_fruit else row['Quality']
                labels.append(self.encoder.transform([label])[0])
            except Exception as e:
                print(f"Error loading image {img_path}: {e}")

        return np.array(images), np.array(labels)

print("DataGenerator class defined")

