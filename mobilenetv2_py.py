def get_keras_architecture(model_path, model_name, category):
    """Extract Keras model architecture as table and blocks."""
    try:
        model = tf.keras.models.load_model(model_path, compile=False)
        # Capture model.summary()
        stream = StringIO()
        model.summary(print_fn=lambda x: stream.write(x + '\n'))
        summary_str = stream.getvalue()

        # Table data
        table_data = []
        total_params = 0
        for layer in model.layers:
            try:
                output_shape = str(layer.output.shape)
            except:
                output_shape = str(model.input_shape) if 'input' in layer.name.lower() else 'Unknown'
            trainable_params = int(np.sum([tf.keras.backend.count_params(w) for w in layer.trainable_weights]))
            non_trainable_params = int(np.sum([tf.keras.backend.count_params(w) for w in layer.non_trainable_weights]))
            table_data.append({
                'layer_name': layer.name,
                'layer_type': layer.__class__.__name__,
                'output_shape': output_shape,
                'trainable_params': trainable_params,
                'non_trainable_params': non_trainable_params
            })
            total_params += trainable_params + non_trainable_params

        # Block data (JSON)
        block_data = {
            'model_name': model_name,
            'category': category,
            'type': 'Keras',
            'input_shape': str(model.input_shape),
            'output_shape': str(model.output_shape) if model.output_shape else 'Unknown',
            'layers': table_data,
            'total_parameters': total_params,
            'summary_text': summary_str
        }

        tf.keras.backend.clear_session()
        return table_data, block_data
    except Exception as e:
        print(f"Error processing Keras model {model_path}: {e}")
        return None, None

def get_tflite_architecture(model_path, model_name, category):
    """Extract TFLite model architecture as table and blocks."""
    try:
        interpreter = tf.lite.Interpreter(model_path=model_path)
        interpreter.allocate_tensors()
        input_details = interpreter.get_input_details()
        output_details = interpreter.get_output_details()
        tensor_details = interpreter.get_tensor_details()

        # Table data
        table_data = []
        for op_idx in range(interpreter._interpreter.NumNodes()):
            op_details = interpreter._interpreter.NodeInputs(op_idx)
            op_outputs = interpreter._interpreter.NodeOutputs(op_idx)
            op_name = interpreter._interpreter.NodeName(op_idx)
            table_data.append({
                'operation_index': op_idx,
                'operation_name': op_name,
                'input_tensors': ', '.join([tensor_details[i]['name'] if i != -1 else 'None' for i in op_details]),
                'output_tensors': ', '.join([tensor_details[i]['name'] for i in op_outputs])
            })

        # Block data (JSON)
        block_data = {
            'model_name': model_name,
            'category': category,
            'type': 'TFLite',
            'input_shape': [d['shape'].tolist() for d in input_details],
            'output_shape': [d['shape'].tolist() for d in output_details],
            'operations': table_data,
            'total_operations': len(table_data)
        }

        return table_data, block_data
    except Exception as e:
        print(f"Error processing TFLite model {model_path}: {e}")
        return None, None

